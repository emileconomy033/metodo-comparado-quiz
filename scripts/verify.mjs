import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script, runInNewContext} from 'node:vm';
const html=readFileSync('index.html','utf8');
const rules=readFileSync('firestore.rules','utf8');
const config=readFileSync('firebase-config.js','utf8');
const inline=html.match(/<script>\s*([\s\S]*?)\s*<\/script>/);
assert(inline,'No existe el script principal');
new Script(inline[1],{filename:'index.html'});
new Script(config,{filename:'firebase-config.js'});
const start=inline[1].indexOf('const QUIZ=');
const stop=inline[1].indexOf('const $=',start);
assert(start>=0&&stop>start,'No se encontró el contenido curricular');
const data=runInNewContext(inline[1].slice(start,stop)+';globalThis.data={QUIZ,PEDAGOGY}',{}).data;
assert.equal(data.QUIZ.length,6,'Deben mantenerse seis preguntas');
assert.equal(data.PEDAGOGY.length,6,'Debe existir interpretación para cada pregunta');
for(let i=0;i<6;i++){
 const q=data.QUIZ[i],p=data.PEDAGOGY[i];
 assert.equal(q.a.length,4,'Opciones incorrectas en P'+(i+1));
 assert(Number.isInteger(q.correct)&&q.correct>=0&&q.correct<4);
 assert.equal(p.mis.length,4,'Faltan distractores en P'+(i+1));
 for(let j=0;j<4;j++)if(j!==q.correct)assert(p.mis[j]?.trim(),'Sin interpretación de distractor P'+(i+1)+'-'+j);
 assert(q.why&&p.principle&&p.transfer&&p.question);
}
for(const id of ['projectionButton','projectChart','finalLearning','submittedPanel','projectExit'])assert(html.includes('id="'+id+'"'),'Falta '+id);
assert(html.includes('function renderLearningSummary('));
assert(html.includes('function renderProjection('));
assert(html.includes('function interpret('));
assert(html.includes('function watchSharedVotes(){'));
assert(!html.includes("collection('participants').onSnapshot(s=>{people=s.docs")||html.includes("if(isHost)stops.push(rref().collection('participants')"),'Lista de participantes sin restricción de host');
assert.equal((rules.match(/allow list: if owner\(id\);/g)||[]).length,2,'Las listas sensibles deben pertenecer al moderador');
assert(rules.includes('allow get: if owner(id) || (signed() && request.auth.uid == pid && participant(id));'));
assert(!rules.includes('if true;'),'Reglas permisivas');
assert(rules.includes("sessionKind in ['practice','official']"));
assert(html.includes('id="moderatorLogin"'));
assert(html.includes('id="durationFields"'));
assert(html.includes('signInWithEmailAndPassword('));
assert(!html.includes('123Moderador'),'Nunca incluir contraseña en el código público');
assert(html.includes("questionTimes:$('mode').value==='competition'?times:Array(N).fill(DEFAULT_SECONDS)"));
assert(html.includes('function questionSeconds(i)'));
assert(rules.includes('allow create: if moderator()'),'La creación debe exigir moderador autenticado');
assert(rules.includes("sign_in_provider == 'password'"));
assert(rules.includes('validTimes(request.resource.data.questionTimes)'));
assert(rules.includes("duration.value(parent(id).data.get('questionTimes'"),'Reglas sin temporizador por pregunta');
assert(html.includes('const pendingVotes=new Set()'));
assert(html.includes('b.disabled=locked||pendingVotes.has(i)'),'Los votos anteriores no deben bloquear las opciones');
assert(html.includes("No fue posible ingresar ('+stage+')"),'Sin diagnóstico de etapa al ingresar');
assert(rules.includes('request.resource.data.diff(resource.data).affectedKeys().hasOnly'), 'Falta controlar qué campos se pueden modificar');
assert(rules.includes('allow update: if signed() && request.auth.uid == pid && participant(id)'),'Solo el votante puede corregir su respuesta');
assert(html.includes('Actividad académica del Grupo 1.</footer>'));
for(const id of ['competitionScore','revealScore','finalScore','personalReveal'])assert(html.includes('id="'+id+'"'),'Falta elemento de retroalimentación: '+id);
assert(html.includes('class="icap-logo"'),'Falta el logo ICAP');
assert(html.includes('function scoreReleased()'));
assert(html.includes('function celebrateCorrect(i)'));
assert(html.includes('function drawPersonalReveal()'));
assert(html.includes('celebratedReveals.has(key)'),'La celebración no debe repetirse cada vez que llega una actualización');
assert(html.includes('prefers-reduced-motion'),'Las animaciones deben respetar movimiento reducido');
assert(html.includes("isQuestionRevealed(i)"),'Solo puntuar respuestas reveladas');
assert(html.includes('¿Por qué no?: '),'Se requiere retroalimentación por distractor seleccionado');
console.log('OK: currículo, moderación, tiempos, privacidad, corrección de votos, logo, celebración y puntuación progresiva.');
